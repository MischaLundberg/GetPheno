# Helper: get_values_to_match


get_values_to_match_ <- function(multi_inclusions, in_pheno_codes, pheno_requestcol, remove_point_in_diag_request) {
  values_to_match <- NULL
  
  if (!multi_inclusions) {
    # Single inclusion: try to extract codes from in_pheno_codes.
    if (is.character(in_pheno_codes) && length(in_pheno_codes) == 1) {
      values_to_match <- in_pheno_codes
    } else if (is.vector(in_pheno_codes) && is.character(in_pheno_codes)) {
      values_to_match <- in_pheno_codes
    } else if (is.data.frame(in_pheno_codes)) {
      if (pheno_requestcol %in% colnames(in_pheno_codes)) {
        values_to_match <- in_pheno_codes[[pheno_requestcol]]
      } else {
        stop("pheno_requestcol not found in in_pheno_codes")
      }
    } else {
      stop("Unexpected type for in_pheno_codes")
    }
    
    # If remove_point_in_diag_request is TRUE and codes are “empty” (or you wish to remove periods)
    # then remove any "." from the codes.
    if (remove_point_in_diag_request && all(values_to_match == "")) {
      cat("INFO: Removing '.' in your pheno request codes. If you don't want this, use --skip_icd_update\n")
      if (is.vector(in_pheno_codes) && is.character(in_pheno_codes)) {
        values_to_match <- gsub("\\.", "", in_pheno_codes)
      } else if (is.data.frame(in_pheno_codes)) {
        values_to_match <- gsub("\\.", "", in_pheno_codes[[pheno_requestcol]])
      }
    } else if (is.character(values_to_match) && all(values_to_match == "")) {
      if (!is.vector(in_pheno_codes)) {
        values_to_match <- unique(as.character(in_pheno_codes[[pheno_requestcol]]))
      } else {
        values_to_match <- in_pheno_codes
      }
    } else if ((is.vector(values_to_match) || is.data.frame(values_to_match)) && length(values_to_match) == 0) {
      if (!is.vector(in_pheno_codes)) {
        values_to_match <- unique(as.character(in_pheno_codes[[pheno_requestcol]]))
      } else {
        values_to_match <- in_pheno_codes
      }
    }
    values_to_match <- unique(as.character(values_to_match))
    cat("Values to match (single inclusion):\n")
    print(values_to_match)
    
  } else {
    # Multi-inclusions case:
    if (is.character(in_pheno_codes) && length(in_pheno_codes) == 1) {
      values_to_match <- in_pheno_codes
    } else if (is.vector(in_pheno_codes) && is.character(in_pheno_codes)) {
      values_to_match <- in_pheno_codes
    } else if (is.data.frame(in_pheno_codes)) {
      if ("Disorder Codes" %in% colnames(in_pheno_codes)) {
        # Use the first row's Disorder Codes and convert it to a unique set of characters.
        values_to_match <- unique(as.character(in_pheno_codes[1, "Disorder Codes"]))
      } else {
        stop("Disorder Codes column not found in in_pheno_codes for multi-inclusion")
      }
    }
    cat("Values to match (multi-inclusion):\n")
    print(values_to_match)
  }
  
  return(values_to_match)
}

