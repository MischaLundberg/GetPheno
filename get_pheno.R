merge_IIDs <- function(tmp_result_df, diagnostic_col, birthdatecol,
                       input_date_in_name, input_date_out_name, iidcol,
                       verbose, Cases, Covariates = FALSE, BuildEntryExitDates = FALSE) {
  
  if (verbose) {
    cat("In merge_IIDs: Cases:", Cases, ", Covariates:", Covariates, 
        ",", input_date_in_name, ",", input_date_out_name, ",", 
        paste(colnames(tmp_result_df), collapse = ", "), 
        ", BuildEntryExitDates:", BuildEntryExitDates, "\n")
  }
  
  # If not Cases, keep only certain columns
  if (!Cases) {
    cols_to_use <- c(iidcol, diagnostic_col, input_date_in_name, input_date_out_name)
    if (birthdatecol %in% colnames(tmp_result_df)) {
      cols_to_use <- c(cols_to_use, birthdatecol)
    }
    if ("type" %in% colnames(tmp_result_df)) {
      cols_to_use <- c(cols_to_use, "type")
    }
    # Retain only those columns that exist
    cols_to_use <- unique(cols_to_use[cols_to_use %in% colnames(tmp_result_df)])
    tmp_result_df <- tmp_result_df[, cols_to_use, drop = FALSE]
  }
  
  # Do the same if Covariates is TRUE
  if (Covariates) {
    cols_to_use <- c(iidcol, diagnostic_col, input_date_in_name, input_date_out_name)
    if (birthdatecol %in% colnames(tmp_result_df)) {
      cols_to_use <- c(cols_to_use, birthdatecol)
    }
    if ("type" %in% colnames(tmp_result_df)) {
      cols_to_use <- c(cols_to_use, "type")
    }
    cols_to_use <- unique(cols_to_use[cols_to_use %in% colnames(tmp_result_df)])
    tmp_result_df <- tmp_result_df[, cols_to_use, drop = FALSE]
  }
  
  # Drop or rename problematic columns
  if ("date_in_y" %in% colnames(tmp_result_df)) {
    cat("WARNING: date_in_y detected in tmp_result_df. This will be dropped (merge_IIDs)\n")
    tmp_result_df$date_in_y <- NULL
  }
  
  if ("date_in_x" %in% colnames(tmp_result_df) && !("date_in" %in% colnames(tmp_result_df))) {
    cat("WARNING: date_in_x detected in tmp_result_df but not date_in. This will be renamed (merge_IIDs)\n")
    tmp_result_df$date_in <- tmp_result_df[["date_in_x"]]
  }
  if ("date_in_x" %in% colnames(tmp_result_df)) {
    cat("WARNING: date_in_x detected in tmp_result_df. This will be dropped (merge_IIDs)\n")
    tmp_result_df$date_in_x <- NULL
  }
  
  # Rename the date_in column if needed
  if (input_date_in_name != "date_in" && !("date_in" %in% colnames(tmp_result_df))) {
    if (verbose) {
      cat("Updating (date_in)", input_date_in_name, "to date_in and dropping", input_date_in_name, "\n")
    }
    tmp_result_df$date_in <- tmp_result_df[[input_date_in_name]]
    tmp_result_df[[input_date_in_name]] <- NULL
  }
  
  # Rename date_out column if needed; otherwise duplicate date_in
  if (input_date_out_name != input_date_in_name && input_date_out_name != "date_out") {
    if (verbose) {
      cat("Updating (date_out)", input_date_out_name, "to date_out and dropping", input_date_out_name, "\n")
    }
    tmp_result_df$date_out <- tmp_result_df[[input_date_out_name]]
    tmp_result_df[[input_date_out_name]] <- NULL
  } else {
    if (verbose) {
      cat("No (date_out) given. Duplicating date_in\n")
      cat("Columns:", paste(colnames(tmp_result_df), collapse = ", "), "\n")
    }
