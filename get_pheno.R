generate_random_date <- function(start_date, end_date) {
  start_date <- as.Date(start_date)
  end_date <- as.Date(end_date)
  days_diff <- as.integer(end_date - start_date)
  random_days <- sample(0:days_diff, 1)
  start_date + days(random_days)
}

