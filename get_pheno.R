process_entry <- function(entry, remove_leading, eM, mode, icdprefix = "", remove_point, ICDCM, only_ICD10 = F, only_ICD9 = F, only_ICD8 = F,DK_clusters = c("DBDS","iPSYCH"))
{
    # Convert remove_leading to bool (same behavior as python)
    remove_leading <- tolower(trimws(as.character(remove_leading))) %in% c("true","1","yes","y")

    ## 1) --- HANDLE NUMERIC ENTRIES ---
    if (!is.character(entry)) {
        if (is.numeric(entry) && grepl("^[0-9]+$", as.character(entry))) {
            cat("[process_entry] WARNING: Integer given without information about underlying ICD definition. Interpreting as ICD8.")
            if (only_ICD10) return(NULL)
            return(format_numeric(entry, mode))
        }
        return(if (remove_point) gsub("\\.", "", as.character(entry)) else entry)
    }

    ## 2) --- ATC ENTRIES ---
    if (startsWith(entry, "ATC:")) {
        if (only_ICD10 || only_ICD9 || only_ICD10) return(NULL)
        if (ATC_Requested == "None") ATC_Requested <<- "Some"

        res <- if (remove_leading) sub("^ATC:", "", entry) else entry
        if (mode %in% DK_clusters && remove_leading)
            res <- paste0("ATC:", toupper(gsub("\\.", "", res)))

        return(if (remove_point) gsub("\\.", "", res) else res)
    }

    ## 3) --- ICD8 ---
    if (startsWith(entry, "ICD8:")) {
        if (only_ICD10 || only_ICD9) return(NULL)
        if (mode %in% DK_clusters) {
            new_entry <- sub("^ICD8:", "", entry)
            res <- format_numeric(new_entry, mode)
            entry <- paste0("ICD8:", res)
        }
        res <- if (remove_point) gsub("\\.", "", entry) else entry
        return(if (remove_leading) toupper(sub("^ICD8:", "", res)) else res)
    }

    ## 4) --- ICD9-CM ---
    if (startsWith(entry, "ICD9-CM:")) {
        if (only_ICD10 || only_ICD8) return(NULL)
        if (mode %in% c("ICDCM","default")) {
            res <- toupper(sub("^ICD9-CM:", "", entry))
            res <- if (remove_leading) res else paste0("ICD9-CM:", res)
            return(if (remove_point) gsub("\\.", "", res) else res)
        }
        return(NULL)
    }

    ## 5) --- ICD10-CM ---
    if (startsWith(entry, "ICD10-CM:")) {
        if (only_ICD8 || only_ICD9) return(NULL)
        if (mode %in% c("ICDCM","default") || ICDCM) {
            res <- toupper(sub("^ICD10-CM:", "", entry))
            res <- if (icdprefix != "") paste0(icdprefix, res) else res
            res <- if (remove_leading) res else paste0("ICD10-CM:", res)
            return(if (remove_point) gsub("\\.", "", res) else res)
        }
        return(NULL)
    }

    ## 6) --- ICD9 ---
    if (startsWith(entry, "ICD9:")) {
        if (only_ICD10 || only_ICD8) return(NULL)
        if (mode %in% DK_clusters) return(NULL)
        res <- toupper(sub("^ICD9:", "", entry))
        res <- if (remove_leading) res else paste0("ICD9:", res)
        return(if (remove_point) gsub("\\.", "", res) else res)
    }

    ## 7) --- ICD10 & prefix logic ---
    if (startsWith(entry, "ICD10:") || (icdprefix != "" && startsWith(entry, icdprefix))) {

        cat(sprintf("[process_entry] Within ICD10 section; mode: %s; entry: %s; ICD prefix: %s",
                            mode, entry, icdprefix))

        if (icdprefix != "") {
            if (!startsWith(entry, "ICD10:") && !startsWith(entry, icdprefix)) {
                res <- paste0("ICD10:", icdprefix, toupper(sub("^ICD10:", "", entry)))
            } else if (startsWith(entry, icdprefix)) {
                res <- toupper(entry)
                res <- if (remove_leading) res else paste0("ICD10:", res)
            } else if (startsWith(entry, paste0("ICD10:", icdprefix))) {
                res <- toupper(entry)
                res <- if (remove_leading) sub("^ICD10:", "", res) else res
            } else if (startsWith(entry, "ICD10:")) {
                res <- toupper(sub("^ICD10:", "", entry))
                res <- icdprefix %||% "" %+% res
                res <- if (remove_leading) res else paste0("ICD10:", res)
            }
        } else {
            res <- toupper(sub("^ICD10:", "", entry))
            res <- if (remove_leading) res else paste0("ICD10:", res)
        }

        res <- if (remove_point) gsub("\\.", "", res) else res
        cat(sprintf("[process_entry] Within ICD10 section; entry=%s -> %s", entry, res))
        return(res)
    }

    ## 8) --- NON-PREFIXED ENTRIES ---
    entry_clean <- trimws(entry)
    res <- entry_clean

    if (mode %in% DK_clusters && !grepl("^[0-9]+$", entry) && !startsWith(toupper(res), "ATC")) {

        if (grepl("^[A-Za-z]{2}[0-9]", entry_clean)) {
            res <- toupper(gsub("\\.", "", entry_clean))
            res <- if (remove_leading) res else paste0("ICD10:", res)

        } else if (grepl("^[A-Za-z](?:[0-9]|$)", entry_clean)) {
            normalized <- toupper(gsub("\\.", "", entry_clean))
            res <- paste0(icdprefix, normalized)
            res <- if (remove_leading) res else paste0("ICD10:", res)

        } else {
            res <- gsub("\\.", "", entry_clean)
        }

        cat(sprintf("[process_entry] DK-mode final: %s -> %s", entry, res))

    } else {
        res <- if (remove_point) gsub("\\.", "", entry_clean) else entry_clean
        res <- if (icdprefix == "") res else paste0(icdprefix, res)
        res <- if (remove_leading) res else paste0("ICD10:", res)
        cat(sprintf("[process_entry] Standard: %s -> %s", entry, res))
    }

    ## 9) --- Remove known prefixes after full processing ---
    tags <- c("ATC:","ICD8:","ICD9:","ICD10:","ICD9-CM:","ICD10-CM:","ICD9CM:","ICD10CM:")
    for (tag in tags) {
        if (startsWith(toupper(res), toupper(tag))) {
            if (remove_leading)
                res <- sub(tag, "", res, ignore.case=TRUE)
            break
        }
    }

    if (remove_point)
        res <- gsub("\\.", "", res)

    cat(sprintf("[process_entry] Final output: %s", res))
    return(res)
}

update_icd_coding <- function(data,
                              eM = FALSE,
                              skip = FALSE,
                              remove_point_in_diag_request = FALSE,
                              ICDCM = FALSE,
                              no_Fill = FALSE,
                              noLeadingICD = FALSE,
                              icdprefix = "",
                              only_ICD10 = FALSE,
                              only_ICD9 = FALSE,
                              only_ICD8 = FALSE,
                              cluster_run = "default",
                              verbose = FALSE,
                              DK_clusters = c("DBDS","iPSYCH")) 
{
    cat(sprintf("[update_icd_coding] Starting update_icd_coding with the following codes to update: %s", 
                        paste(data, collapse=", ")))

    # Convert data to list
    # Convert from dataframe to vector of ICD entries
    if (is.data.frame(data)) {
        data <- as.character(data[[1]])
    }
    

    if (skip) {
        return(data)
    }

    output_list <- list()
    print_which_section <- TRUE

    # Determine mode priority:
    if (ICDCM) {
        if (print_which_section) {
            cat("[update_icd_coding] Processing only CM ICD codes in update_icd_coding")
            print_which_section <- FALSE
        }
    }

    if (only_ICD10) {
        if (print_which_section && !ICDCM) {
            cat("[update_icd_coding] Processing only ICD10 codes in update_icd_coding")
            print_which_section <- FALSE
        }
    } else if (only_ICD9 && !ICDCM) {
        if (print_which_section) {
            cat("[update_icd_coding] Processing only ICD9 codes in update_icd_coding")
            print_which_section <- FALSE
        }
    } else if (only_ICD8 && !ICDCM) {
        if (print_which_section) {
            cat("[update_icd_coding] Processing only ICD8 codes in update_icd_coding")
            print_which_section <- FALSE
        }
    }

    if (verbose) {
        cat(sprintf("[update_icd_coding] noLeadingICD is set to: %s", noLeadingICD))
    }

    output_list <- list()

    for (entry in data) {
        p <- process_entry(
            entry          = entry,
            remove_leading = noLeadingICD,
            eM             = eM,
            mode           = cluster_run,
            icdprefix      = icdprefix,
            remove_point   = remove_point_in_diag_request,
            ICDCM          = ICDCM,
            only_ICD10     = only_ICD10, 
            only_ICD9      = only_ICD9, 
            only_ICD8      = only_ICD8, 
            DK_clusters    = DK_clusters
        )

        cat(sprintf("[update_icd_coding] Processing entry [process_entry]: entry=%s; remove_leading=%s; eM=%s; mode=%s; icdprefix=%s; remove_point=%s; ICDCM=%s. Result: %s", 
                            entry, noLeadingICD, eM, cluster_run, 
                            icdprefix, remove_point_in_diag_request, ICDCM, p))

        if (!is.null(p)) {
            output_list <- append(output_list, p)
        }
    }

    if (verbose) {
        cat(paste("[update_icd_coding] output_list before mode check:", paste(output_list, collapse=", ")))
    }

    # If cluster mode excludes CM codings
    if (cluster_run %in% DK_clusters) {
        output_list <- Filter(function(entry) {
            !(is.character(entry) &&
              (startsWith(entry, "ICD10-CM:") || startsWith(entry, "ICD9-CM:")))
        }, output_list)
    }

    cat(sprintf("[update_icd_coding] Final updated ICD codes: %s",
                        paste(output_list, collapse=", ")))

    if (!verbose) {
        cat(sprintf("[update_icd_coding] Final updated ICD codes: %s\n",
                    paste(output_list, collapse=", ")))
    }

    return(output_list)
}

process_ExDEP_exclusions <- function(data, iidcol, diagcol, dx_name, dates_name, verbose, update_diag_col_name_to_diag, get_earliest_date_from_data = FALSE) {
  if (update_diag_col_name_to_diag && diagcol %in% colnames(data)) {
    names(data)[names(data) == diagcol] <- "diagnosis"
  }
  if (verbose) {
    cat("data columns:\n"); print(colnames(data))
    print(head(data, 2))
  }
  # Group by IID using dplyr
  dx_string <- data %>% group_by_at(iidcol) %>% summarise(diagnoses = first(diagnosis)) %>% ungroup()
  in_dates <- data %>% group_by_at(iidcol) %>% summarise(in_dates = first(date_in)) %>% ungroup()
  if (get_earliest_date_from_data) {
    earliest_in_dates <- data %>% group_by_at(iidcol) %>% summarise(first_dx = min(date_in, na.rm = TRUE)) %>% ungroup()
    id_dx_date_df <- dx_string %>% left_join(in_dates, by = iidcol) %>% left_join(earliest_in_dates, by = iidcol)
  } else {
    id_dx_date_df <- dx_string %>% left_join(in_dates, by = iidcol)
  }
  names(id_dx_date_df)[names(id_dx_date_df) == "diagnoses"] <- dx_name
  names(id_dx_date_df)[names(id_dx_date_df) == "in_dates"] <- dates_name
  if (verbose) {
    print(head(id_dx_date_df, 2))
    print(colnames(id_dx_date_df))
  }
  rm(data)
  return(id_dx_date_df)
}


