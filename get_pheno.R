  if (verbose) cat("Running awk command:\n", awk_command, "\n")
  system(awk_command, intern = TRUE)
  if (!verbose) file.remove(index_file)
}

load_lpr_file <- function(lpr_file, dta_input, fsep, lpr_cols_to_read_as_date, DateFormat, potential_lpr_cols_to_read_as_date) {
  if (dta_input) {
    library(haven)
    read_dta(lpr_file)
  } else {
    df_header <- read_delim(lpr_file, delim = fsep, col_types = cols(.default = "c"), n_max = 0)
    if (!is.null(lpr_cols_to_read_as_date) && length(lpr_cols_to_read_as_date) > 0) {
      available_date_cols <- intersect(lpr_cols_to_read_as_date, colnames(df_header))
      cat("Date columns to parse:", available_date_cols, "\n")
    } else {
      available_date_cols <- intersect(potential_lpr_cols_to_read_as_date, colnames(df_header))
      cat("Inferring date columns:", available_date_cols, "\n")
    }
    if (length(available_date_cols) > 0) {
      tryCatch({
        read_delim(lpr_file, delim = fsep, col_types = cols(.default = "c"))
      }, error = function(e) {
        df <- read_delim(lpr_file, delim = fsep, col_types = cols(.default = "c"))
        for (col in available_date_cols) {
          df[[col]] <- as.Date(df[[col]], format = DateFormat)
        }
        df
      })
    } else {
      read_delim(lpr_file, delim = fsep, col_types = cols(.default = "c"))
    }
  }
}

merge_secondary_diagnoses <- function(df1, df, diagnostic_col, lpr_recnummer, lpr2nd_recnummer, diagnostic2nd_col) {
  # df <- df %>% rename(!!lpr_recnummer := !!sym(lpr2nd_recnummer),
  #                     !!diagnostic_col := !!sym(diagnostic2nd_col))
  df <- df %>% rename(
    !!rlang::sym(lpr_recnummer) := !!rlang::sym(lpr2nd_recnummer),
    !!rlang::sym(diagnostic_col) := !!rlang::sym(diagnostic2nd_col)
  )
  df1_temp <- inner_join(df %>% select(!!sym(diagnostic_col), !!sym(lpr_recnummer)),
                         df1 %>% select(-one_of(diagnostic_col)), by = lpr_recnummer)
  df1_temp <- distinct(df1_temp)
  if ("c_tildiag" %in% colnames(df1_temp) && "c_diagtype" %in% colnames(df1_temp)) {
    df1_temp <- df1_temp %>% mutate(!!diagnostic_col := if_else(str_detect(c_diagtype, "\\+"), c_tildiag, .data[[diagnostic_col]]))
  }
  bind_rows(df1, df1_temp)
}

process_lpr_data <- function(lpr_file, lpr2nd_file, dta_input, fsep, lpr_cols_to_read_as_date, DateFormat,
                             potential_lpr_cols_to_read_as_date, diagnostic_col, diagnostic2nd_col,
                             lpr_recnummer, lpr2nd_recnummer) {
  file_paths <- if (grepl(",", lpr_file)) unlist(strsplit(lpr_file, ",")) else list(lpr_file)
  if (lpr2nd_file != "") {
    secondary_paths <- if (grepl(",", lpr2nd_file)) unlist(strsplit(lpr2nd_file, ",")) else list(lpr2nd_file)
  } else {
    secondary_paths <- list()
  }
  df1 <- data.frame()
  if (length(secondary_paths) > 0) {
    for (i in seq_along(file_paths)) {
      df_lpr <- load_lpr_file(file_paths[[i]], dta_input, fsep, lpr_cols_to_read_as_date, DateFormat, potential_lpr_cols_to_read_as_date)
      df_lpr2nd <- load_lpr_file(secondary_paths[[i]], dta_input, fsep, lpr_cols_to_read_as_date, DateFormat, potential_lpr_cols_to_read_as_date)
      df_merged <- merge_secondary_diagnoses(df_lpr, df_lpr2nd, diagnostic_col, lpr_recnummer, lpr2nd_recnummer, diagnostic2nd_col)
      df1 <- bind_rows(df1, df_merged)
    }
  } else {
    for (fp in file_paths) {
      df_lpr <- load_lpr_file(fp, dta_input, fsep, lpr_cols_to_read_as_date, DateFormat, potential_lpr_cols_to_read_as_date)
      df1 <- bind_rows(df1, df_lpr)
    }
  }
  df1
}

