        df1 <- bind_rows(df1, df)
      }
      rm(file_paths)
    } else {
      if (dta_input) {
        df_temp <- read_dta(lpr_file)
        filtered_chunk <- df_temp %>% filter((.data[[iidcol]]) %in% iid_batch)
        df1 <- bind_rows(df1, filtered_chunk)
      } else {
