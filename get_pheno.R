update_DxDates_ExDEP_multi_exclusion <- function(all_data, exclusion_type, exc_diag, exc_diag_date,
                                                 exc_diag_inflicted_changes, diag_excode, level2codes,
                                                 level2dates, level2datemodifiercodes, level2datemodifierdates,
                                                 level2datemodifierDXs, verbose = FALSE) {
  # This function updates diagnosis dates for each individual based on exclusion criteria.
  # Parameters:
  #   all_data: data frame with one row per individual. Expected to include:
  #       - in_dates: a list-column of diagnosis dates (as Date objects or strings)
  #       - diagnoses: a list-column of diagnosis codes (strings)
  #       - first_dx: the originally computed first diagnosis date (if available)
  #   exc_diag: vector of ICD codes that trigger exclusion
  #   exc_diag_date: vector or list (per individual) of dates when an exclusion diagnosis occurred
  #   exc_diag_inflicted_changes: a string (prefix) used to flag changes due to exclusions
  #   diag_excode: (optional) additional exclusion code(s)
  #   level2codes, level2dates: secondary codes and dates (if any) for further exclusion logic
  #   level2datemodifiercodes, level2datemodifierdates, level2datemodifierDXs:
  #       additional codes/dates used to modify the adjusted first diagnosis date
  #   verbose: if TRUE, print debugging messages.
  #
  # The function creates (if not present) new columns:
  #   - ExDEP_excluded: logical flag for exclusion
  #   - ExDEP_exclusion_reason: a text summary of which exclusion code(s) were found
  #   - ExDEP_adjusted_first_dx: the new “first diagnosis” date after applying exclusions
  #   - ExDEP_dX_lost_percent: percentage (0–100) of diagnoses “lost” (i.e. that occurred before exclusion)
  
  # Ensure the new columns exist
  if (!("ExDEP_excluded" %in% colnames(all_data))) {
    all_data$ExDEP_excluded <- FALSE
  }
  if (!("ExDEP_exclusion_reason" %in% colnames(all_data))) {
    all_data$ExDEP_exclusion_reason <- NA
  }
  if (!("ExDEP_adjusted_first_dx" %in% colnames(all_data))) {
    all_data$ExDEP_adjusted_first_dx <- as.Date(NA)
  }
  if (!("ExDEP_dX_lost_percent" %in% colnames(all_data))) {
    all_data$ExDEP_dX_lost_percent <- 0
  }
  
  # Process each individual (row) separately.
  for (i in seq_len(nrow(all_data))) {
    person <- all_data[i, ]
    
    # Expect that the diagnosis dates and codes are stored as list elements.
    diag_dates <- unlist(person$in_dates)
    diag_codes <- unlist(person$diagnoses)
    
    # Skip if no diagnoses are present.
    if (length(diag_dates) == 0 || length(diag_codes) == 0) next
    
    # Ensure dates are Date objects.
    diag_dates <- as.Date(diag_dates)
    
    # Determine the original first diagnosis date (if already computed, use it; otherwise, take min)
    first_dx <- if ("first_dx" %in% names(person) && !is.na(person$first_dx)) {
      as.Date(person$first_dx)
    } else {
      min(diag_dates, na.rm = TRUE)
    }
    
    # Find all diagnoses that match one of the exclusion codes and occurred on or before first_dx.
    excl_indices <- which(diag_codes %in% exc_diag & diag_dates <= first_dx)
    
    if (length(excl_indices) > 0) {
      # Mark the individual as excluded.
      all_data$ExDEP_excluded[i] <- TRUE
      # Record the exclusion reason (list the matching codes and their dates).
      reasons <- paste0(diag_codes[excl_indices], " on ", diag_dates[excl_indices], collapse = "; ")
      all_data$ExDEP_exclusion_reason[i] <- reasons
      
      # For the adjusted first diagnosis date, we try to “remove” the earlier diagnoses.
      max_excl_date <- max(diag_dates[excl_indices], na.rm = TRUE)
      subsequent_indices <- which(diag_dates > max_excl_date)
      if (length(subsequent_indices) > 0) {
        new_first_dx <- min(diag_dates[subsequent_indices], na.rm = TRUE)
        all_data$ExDEP_adjusted_first_dx[i] <- new_first_dx
        # Calculate percentage of diagnoses that occurred before (or on) the exclusion cutoff.
        lost_count <- sum(diag_dates <= max_excl_date)
        total_count <- length(diag_dates)
        lost_percent <- round((lost_count / total_count) * 100, 2)
        all_data$ExDEP_dX_lost_percent[i] <- lost_percent
      } else {
        # If no diagnosis remains after the exclusion, keep the original first_dx.
        all_data$ExDEP_adjusted_first_dx[i] <- first_dx
        all_data$ExDEP_dX_lost_percent[i] <- 100
      }
      
      if (verbose) {
        cat("Individual", person[[iidcol]], "excluded due to:", reasons, "\n")
      }
    } else {
      # No exclusion diagnosis found: use the original first_dx.
      all_data$ExDEP_adjusted_first_dx[i] <- first_dx
    }
    
    # Process optional level-2 modifier diagnoses (if provided).
    if (!is.null(level2datemodifiercodes) && length(level2datemodifiercodes) > 0) {
      mod_indices <- which(diag_codes %in% level2datemodifiercodes)
      if (length(mod_indices) > 0) {
        mod_dates <- diag_dates[mod_indices]
        new_date <- max(mod_dates, na.rm = TRUE)
        if (new_date > all_data$ExDEP_adjusted_first_dx[i]) {
          all_data$ExDEP_adjusted_first_dx[i] <- new_date
          if (verbose) {
            cat("Individual", person[[iidcol]], "first_dx adjusted (level2 modifier) to", new_date, "\n")
          }
        }
      }
    }
  }
  
  if (verbose) {
    cat("Completed update_DxDates_ExDEP_multi_exclusion\n")
  }
  
  return(all_data)
}

