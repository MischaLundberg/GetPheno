process_ophold <- function(ophold, stam, tmp_result_df, ophold_out_file, birthdatecol, iidcol, verbose) {
  min_code <- 5000
  max_code <- 7000
  cat("Processing ophold: updating DK-born information...\n")
  if (verbose) {
    cat("Using fkode range [", min_code, ",", max_code, "]\n")
  }
  stam <- stam %>% filter(fkode >= min_code & fkode <= max_code) %>%
    mutate(both_parents_DK = FALSE)
  stam <- stam %>% mutate(both_parents_DK = if_else(fkode_m >= min_code & fkode_m <= max_code & 
                                                      fkode_f >= min_code & fkode_f <= max_code, TRUE, FALSE)) %>%
    select(!!sym(iidcol), fkode, !!sym(birthdatecol), both_parents_DK)
  ophold <- left_join(stam, ophold, by = iidcol)
  grouped <- ophold %>% group_by_at(iidcol)
  stat_lists <- grouped %>% summarise(stat = list(stat)) %>% ungroup()
  statd_lists <- grouped %>% summarise(statd = list(statd)) %>% ungroup()
  ophold_df <- left_join(stat_lists, statd_lists, by = iidcol)
  tflytd_lists <- grouped %>% summarise(tflytd = list(tflytd)) %>% ungroup()
  ophold_df <- left_join(ophold_df, tflytd_lists, by = iidcol)
  fflytd_lists <- grouped %>% summarise(fflytd = list(fflytd)) %>% ungroup()
  ophold_df <- left_join(ophold_df, fflytd_lists, by = iidcol)
  komkod_lists <- grouped %>% summarise(komkod = list(komkod)) %>% ungroup()
  ophold_df <- left_join(ophold_df, komkod_lists, by = iidcol)
  orig_lists <- grouped %>% summarise(orig = list(orig)) %>% ungroup()
  ophold_df <- left_join(ophold_df, orig_lists, by = iidcol)
  opholdnr_lists <- grouped %>% summarise(opholdnr = list(opholdnr)) %>% ungroup()
  ophold_df <- left_join(ophold_df, opholdnr_lists, by = iidcol)
  moved_to_dk <- grouped %>% summarise(moved_to_dk = min(fflytd, na.rm = TRUE)) %>% ungroup()
  ophold_df <- left_join(ophold_df, moved_to_dk, by = iidcol)
  if (ophold_out_file != "") {
    write_tsv(ophold_df, ophold_out_file)
    cat("New ophold file stored at", ophold_out_file, "\n")
  }
  if (!missing(tmp_result_df) && !identical(tmp_result_df, "")) {
    dx_result_df <- left_join(tmp_result_df, ophold_df, by = iidcol)
  } else {
    dx_result_df <- ophold_df
  }
  dx_result_df <- distinct(dx_result_df, .data[[iidcol]], .keep_all = TRUE)
  return(dx_result_df)
}

