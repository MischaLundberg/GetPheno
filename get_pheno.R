      }
    }
    if (lpr2nd_file != "" && length(recnums_to_keep) > 0) {
      if (grepl(",", lpr2nd_file)) {
        file_paths <- unlist(strsplit(lpr2nd_file, ","))
      } else {
        file_paths <- list(lpr2nd_file)
      }
      recnum_batch <- recnums_to_keep
      cat("Batch", batch_num, "has", length(recnum_batch), "recnums from secondary diagnoses.\n")
      for (lprfile in file_paths) {
        df1_rows_to_keep <- load_mapping_rows(lprfile, lpr2nd_recnummer, recnum_batch, fsep)
        cat("Keeping rows (first 10):", head(df1_rows_to_keep, 10), "from secondary file", lprfile, "\n")
        temp_file <- paste0(substr(UUIDgenerate::UUIDgenerate(), 1, 4), ".filtered_temp.csv")
        build_temp_file(lprfile, df1_rows_to_keep, temp_file = temp_file, verbose = verbose)
        lprfile <- temp_file
        df_header <- read_delim(lprfile, delim = fsep, col_types = cols(.default = "c"), n_max = 0)
        if (verbose) {
          cat("Header of secondary file:", colnames(df_header), "\n")
        }
        filtered_chunk <- read_delim(lprfile, delim = fsep, col_types = cols(.default = "c"))
        df1_temp <- inner_join(filtered_chunk %>% select(!!sym(diagnostic_col), !!sym(lpr_recnummer)),
                               df1 %>% select(-all_of(diagnostic_col)), by = lpr_recnummer)
        df1_temp <- distinct(df1_temp)
        if ("c_tildiag" %in% colnames(df1_temp)) {
          temp_df <- df1_temp %>% select(-all_of(diagnostic_col)) %>% rename(!!diagnostic_col := c_tildiag)
          df1_temp <- bind_rows(df1_temp, temp_df)
        }
        before_rows <- nrow(df1)
        df1 <- bind_rows(df1, df1_temp)
        cat("Batch", batch_num, "merged secondary file resulted in", nrow(df1), "rows.\n")
        rm(filtered_chunk, df1_temp)
        file.remove(temp_file)
      }
      rm(file_paths)
    }
    gc()
    if (exact_match) {
      cat("Updating diagnostic codes to uppercase.\n")
      df1[[diagnostic_col]] <- toupper(df1[[diagnostic_col]])
    }
    cat("At end of batch", batch_num, "df1 has", nrow(df1), "rows.\n")
    if (first_write) {
      process_pheno_and_exclusions(MatchFI, df1, df3, df4, iidcol, verbose,
                                   ctype_excl, ctype_incl, Filter_YoB, Filter_Gender, use_predefined_exdep_exclusions,
                                   RegisterRun, dst, ipsych_run, dbds_run, cluster_run, exact_match, skip_icd_update,
                                   remove_point_in_diag_request, ICDCM, qced_iids, general_exclusions, multi_inclusions,
                                   in_pheno_codes, pheno_requestcol, diagnostic_col, atc_diag_col, birthdatecol,
                                   atc_date_col, atc_cols_to_read_as_date, atc_file, fsep, BuildEntryExitDates,
                                   lifetime_exclusions_file, post_exclusions_file, oneYearPrior_exclusions_file,
                                   outfile, write_Plink2_format, write_fastGWA_format, write_pickle, n_stam_iids,
                                   exclCHBcontrols, iidstatus_col, addition_information_file, sexcol, input_date_in_name,
                                   input_date_out_name, append = FALSE)
    } else if (nrow(df1) > 0) {
      process_pheno_and_exclusions(MatchFI, df1, df3, df4, iidcol, verbose,
                                   ctype_excl, ctype_incl, Filter_YoB, Filter_Gender, use_predefined_exdep_exclusions,
                                   RegisterRun, dst, ipsych_run, dbds_run, cluster_run, exact_match, skip_icd_update,
                                   remove_point_in_diag_request, ICDCM, qced_iids, general_exclusions, multi_inclusions,
                                   in_pheno_codes, pheno_requestcol, diagnostic_col, atc_diag_col, birthdatecol,
                                   atc_date_col, atc_cols_to_read_as_date, atc_file, fsep, BuildEntryExitDates,
                                   lifetime_exclusions_file, post_exclusions_file, oneYearPrior_exclusions_file,
                                   outfile, write_Plink2_format, write_fastGWA_format, write_pickle, n_stam_iids,
                                   exclCHBcontrols, iidstatus_col, addition_information_file, sexcol, input_date_in_name,
                                   input_date_out_name, append = TRUE)
    } else {
      cat("INFO: Skipping batch", batch_num, "as there are no overlapping cases.\n")
    }
    first_write <- FALSE
  }
}

