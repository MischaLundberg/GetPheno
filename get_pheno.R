        }
        if (multi_diag_cols) {
          df <- df %>% rename(!!diagnostic_col := !!sym(diag_cols[curr]))
          curr <- curr + 1
        }
        cat("Memory after loading", lprfile, "in batch", batch_num, ":\n")
        usage()
        if (lpr2nd_file != "") {
          cat("Loading secondary diagnosis files for batch", batch_num, "\n")
          recnums_to_keep <- c(recnums_to_keep, unique(df[[lpr_recnummer]]))
          recnums_to_keep <- unique(recnums_to_keep)
