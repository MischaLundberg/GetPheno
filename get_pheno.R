batch_load_df1_process_pheno_and_exclusions <- function(lpr_file, batch_size, diagnostic_col, lpr_cols_to_read_as_date, potential_lpr_cols_to_read_as_date, dta_input, MatchFI, df3, iidcol, verbose, ctype_excl, ctype_incl, Filter_YoB, Filter_Gender, use_predefined_exdep_exclusions, RegisterRun, dst, ipsych_run, dbds_run, cluster_run, exact_match, skip_icd_update, remove_point_in_diag_request, ICDCM, qced_iids, general_exclusions, multi_inclusions, in_pheno_codes, pheno_requestcol, atc_diag_col, birthdatecol, atc_date_col, atc_cols_to_read_as_date, atc_file, fsep, BuildEntryExitDates, lifetime_exclusions_file, post_exclusions_file, oneYearPrior_exclusions_file, outfile, write_Plink2_format, write_fastGWA_format, write_pickle, n_stam_iids, exclCHBcontrols, iidstatus_col, addition_information_file, sexcol, input_date_in_name, input_date_out_name, df4) {
  iids <- unique(df3[[iidcol]])
  batch_size <- as.integer(batch_size)
  num_batches <- ceiling(length(iids) / batch_size)
  first_write <- TRUE
  df3backup <- df3
  df1 <- data.frame()
  for (batch_num in seq_len(num_batches)) {
    start_idx <- (batch_num - 1) * batch_size + 1
    end_idx <- start_idx + batch_size - 1
    iid_batch <- iids[start_idx:min(end_idx, length(iids))]
    df3 <- df3backup %>% filter((.data[[iidcol]]) %in% iid_batch)
    n_stam_iids <- n_distinct(df3[[iidcol]])
    cat("Processing batch", batch_num, "of", num_batches, "with", length(iid_batch), "IIDs: ", head(iid_batch, 5), "\n")
    recnums_to_keep <- c()
    if (grepl(",", lpr_file)) {
      file_paths <- unlist(strsplit(lpr_file, ","))
      multi_diag_cols <- FALSE
      if (grepl(",", diagnostic_col)) {
        diag_cols <- unlist(strsplit(diagnostic_col, ","))
        multi_diag_cols <- TRUE
        diagnostic_col <- diag_cols[1]
        curr <- 1
      }
      df1 <- data.frame()
      for (lprfile in file_paths) {
        df <- data.frame()
        if (dta_input) {
          df_temp <- read_dta(lprfile)
          filtered_chunk <- df_temp %>% filter((.data[[iidcol]]) %in% iid_batch)
          df <- bind_rows(df, filtered_chunk)
