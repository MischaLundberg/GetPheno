  for (i in seq_len(nrow(case_rows))) {
    src <- 0; tgt <- length(c("MDD", "Age", "ID", "SCZ", "BPD", "DEM", "AUD", "DUD", "MCI", "CTI", "ClinPlausMDD")) - 1
    key <- paste(src, tgt, sep = "-")
