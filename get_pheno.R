split_and_format <- function(input_str, fill = FALSE) {
  if (grepl(":", input_str)) {
    m <- str_match(input_str, "([A-Za-z]+)(\\d+)(?:\\.(\\d+))?")
  } else {
    m <- str_match(input_str, "([A-Za-z]*)(\\d+)(?:\\.(\\d+))?")
  }
  if (!is.na(m[1,1])) {
    string_part <- m[1,2]
    integer_part <- m[1,3]
    decimal_part <- m[1,4]
    if (is.na(decimal_part)) {
      combined_number <- integer_part
    } else {
      combined_number <- paste0(integer_part, decimal_part)
    }
    if (fill) {
      combined_number <- str_pad(combined_number, width = 4, side = "right", pad = "0")
    }
    final_string <- paste0(string_part, combined_number)
    return(final_string)
  } else {
    stop("Input string format is invalid: ", input_str)
  }
}

